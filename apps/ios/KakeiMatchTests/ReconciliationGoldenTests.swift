import Foundation
import Testing
@testable import KakeiMatch

private final class ReconciliationTestBundle {}
struct ReconciliationGoldenTests {
    struct Receipt: Decodable {
        var receiptId: String; var actualTransactionId: String; var merchant: String
        var purchasedDate: KMDate; var amountYen: Int; var actualAccountId: String
        var input: KMReconciliationReceipt { .init(receiptId: receiptId, actualTransactionId: actualTransactionId, merchant: merchant,
            purchasedDate: purchasedDate, amountYen: amountYen, actualAccountId: actualAccountId) }
    }
    struct Case: Decodable {
        var id: String
        var statements: [KMStatementTransaction]
        var receipts: [Receipt]
        var preferred: [String: Set<String>]
        var expected: KMReconciliationResult
    }
    @Test func all33EvaluationCasesAnd240NumericBoundaryCasesMatchTS() throws {
        // Generated by executing the unmodified TS engine. Synthetic inputs only.
        let bundle = Bundle(for: ReconciliationTestBundle.self)
        let url = try #require(bundle.url(forResource: "reconciliation-parity", withExtension: "json"))
        let cases = try KMJSON.decoder().decode([Case].self, from: Data(contentsOf: url))
        #expect(cases.count == 273)
        for item in cases {
            let actual = KMReconciliationEngine.run(statements: item.statements, receipts: item.receipts.map(\.input), preferredAccountIds: item.preferred)
            #expect(actual.statementResults == item.expected.statementResults, "\(item.id)")
            #expect(actual.receiptResults == item.expected.receiptResults, "\(item.id)")
            #expect(actual.candidates.count == item.expected.candidates.count, "\(item.id)")
            for (candidate, expected) in zip(actual.candidates, item.expected.candidates) {
                var normalized = candidate
                // JSON's shortest decimal encoding of a binary ratio and Decimal's exact expansion
                // describe the same binary64 value; compare that projection within 1e-15.
                #expect(abs(candidate.merchantSimilarity - expected.merchantSimilarity) < Decimal(string: "0.000000000000001")!, "\(item.id)")
                normalized.merchantSimilarity = expected.merchantSimilarity
                #expect(normalized == expected, "\(item.id)")
            }
        }
    }
    @Test func binary64RoundingAndMarginAreNotDecimalArithmetic() {
        // JS: 1 - 0.85 = 0.15000000000000002; 0.9 - 0.75 = 0.15000000000000002.
        #expect(KMJSNumber(1) - KMJSNumber("0.85") > KMJSNumber("0.15"))
        #expect(KMJSNumber("0.9") - KMJSNumber("0.75") > KMJSNumber("0.15"))
        #expect((KMJSNumber("0.55") + KMJSNumber("0.3") + KMJSNumber("0.05")).roundedMillion().decimal == Decimal(string: "0.9")!)
        #expect(KMJSNumber("0.1234565").roundedMillion().decimal == Decimal(string: "0.123457")!)
    }
}
