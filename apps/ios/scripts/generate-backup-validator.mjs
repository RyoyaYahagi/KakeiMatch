// Generates an offline JavaScriptCore validator from the reference schemas, including Zod refinements.
// Run from the repository after pnpm install: node apps/ios/scripts/generate-backup-validator.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const require = createRequire(path.join(root, 'apps/pwa/package.json'));
const { build } = createRequire(require.resolve('vite'))('esbuild');
const source = await readFile(path.join(root, 'src/lib/local-backup-format.ts'), 'utf8');
const slice = (start, end) => source.slice(source.indexOf(start), source.indexOf(end));
const input = slice('import ', 'export type PortableBackupManifest')
  .split('\n').filter(line => !line.includes('new TextEncoder') && !line.includes('new TextDecoder')).join('\n')
  + '\n' + slice('function fail(', 'async function hash(')
  + '\n' + slice('function recordValueSchema(', 'function expectedMissingArtifacts(')
  + `\nexport function validate(manifestJSON: string, localJSON: string): string {
    try {
      const manifest = manifestSchema.parse(JSON.parse(manifestJSON));
      const local = validateLocalData(JSON.parse(localJSON));
      if (local.blobs.length !== 0) throw new Error('inline blobs');
      return JSON.stringify({ manifest, local });
    } catch { return JSON.stringify({ error: 'バックアップの目録または端末記録が未対応・不正です。' }); }
  }`;
const result = await build({ stdin: { contents: input, sourcefile: 'ios-backup-validator.ts', resolveDir: path.join(root, 'src/lib'), loader: 'ts' },
  bundle: true, write: false, format: 'iife', globalName: 'KMBackupValidation', platform: 'browser', target: 'safari18',
  minify: true, legalComments: 'inline', treeShaking: true,
  // The Actual engine is not needed by its tree-shaken schema exports.
  external: ['@actual-app/api', '@actual-app/api/browser'] });
const output = path.join(root, 'apps/ios/KakeiMatch/Data/Backup/Resources');
await mkdir(output, { recursive: true });
const hashes = await Promise.all(['src/lib/local-backup-format.ts', 'src/lib/local-data.ts', 'src/lib/actual-browser-ledger.ts',
  'src/lib/recurring-schedule.ts', 'src/lib/category-learning.ts', 'src/lib/monthly-budget-settings.ts',
  'src/lib/moneyforward-import-format.ts', 'src/lib/receipt-extraction.ts', 'src/lib/category.ts', 'workers/ai-gateway/src/payroll-schema.ts']
  .map(async file => `${file}: ${createHash('sha256').update(await readFile(path.join(root, file))).digest('hex')}`));
await writeFile(path.join(output, 'backup-validator.js'), '/* eslint-disable */\n// Generated by apps/ios/scripts/generate-backup-validator.mjs. Do not edit.\n' + result.outputFiles[0].text);
await writeFile(path.join(output, 'backup-validator-sources.txt'), hashes.join('\n') + '\n');
